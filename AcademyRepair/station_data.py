@dataclass(frozen=True)
class BuildingSeed:
    template_id: str
    coordinates: list[TileCoordinate] = field(default_factory=list)
    level: int = 1
    status: str = "online"


SectionSpec = tuple[str, str, int, list[BuildingSeed]]
SectionGridDimensions = dict[str, tuple[int, int]]
SectionInvalidSpanMap = dict[str, list[tuple[int, int, int]]]
SectionDefaultFillMap = dict[str, str]


def seed_building(
    template_id: str,
    coordinates: list[TileCoordinate] | None = None,
    level: int = 1,
    status: str = "online",
) -> BuildingSeed:
    return BuildingSeed(
        template_id=template_id,
        coordinates=list(coordinates) if coordinates is not None else [],
        level=level,
        status=status,
    )


def default_fill_sections(specs: list[SectionSpec], template_id: str) -> SectionDefaultFillMap:
    return {section_name: template_id for section_name, _, _, _ in specs}

