def build_section(
    section_id: str,
    name: str,
    purpose: str,
    tile_count: int,
    buildings: list[BuildingSeed],
    grid_dimensions: tuple[int, int] | None = None,
) -> Section:
    grid_rows, grid_columns = grid_dimensions if grid_dimensions is not None else (None, None)
    section = Section(
        section_id=section_id,
        name=name,
        purpose=purpose,
        tile_count=tile_count,
        grid_rows=grid_rows,
        grid_columns=grid_columns,
    )
    return section


def build_floor(
    floor_id: str,
    name: str,
    role: str,
    specs: list[SectionSpec],
    templates: dict[str, BuildingTemplate],
    section_grid_dimensions: SectionGridDimensions | None = None,
    section_invalid_spans: SectionInvalidSpanMap | None = None,
    section_default_fill_templates: SectionDefaultFillMap | None = None,
) -> Floor:
    sections = [
        build_section(
            f"{floor_id}-{index}",
            section_name,
            purpose,
            tile_count,
            buildings,
            (section_grid_dimensions or {}).get(section_name),
        )
        for index, (section_name, purpose, tile_count, buildings) in enumerate(specs, start=1)
    ]
    for section in sections:
        for row_index, start_column, tile_count in (section_invalid_spans or {}).get(section.name, []):
            section.invalidate_span(row_index, start_column, tile_count)
    for section, spec in zip(sections, specs):
        for building_seed in spec[3]:
            section.add_building(
                Building(
                    building_seed.template_id,
                    level=building_seed.level,
                    status=building_seed.status,
                    coordinates=list(building_seed.coordinates),
                ),
                templates,
            )
    for section in sections:
        default_fill_template_id = (section_default_fill_templates or {}).get(section.name)
        if default_fill_template_id is None:
            continue
        for coordinate in section.open_coordinates():
            section.add_building(Building(default_fill_template_id, coordinates=[coordinate]), templates)
    return Floor(floor_id, name, role, sections)


