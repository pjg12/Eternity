def reflect_invalid_spans_horizontally(
    spans: list[tuple[int, int, int]],
    column_count: int,
) -> list[tuple[int, int, int]]:
    return [
        (row_index, column_count - start_column - tile_count, tile_count)
        for row_index, start_column, tile_count in spans
    ]


def reflect_invalid_spans_vertically(
    spans: list[tuple[int, int, int]],
    row_count: int,
) -> list[tuple[int, int, int]]:
    return [
        (row_count - 1 - row_index, start_column, tile_count)
        for row_index, start_column, tile_count in spans
    ]


def reflect_coordinates_horizontally(
    coordinates: list[TileCoordinate],
    column_count: int,
) -> list[TileCoordinate]:
    return [(row_index, column_count - 1 - column_index) for row_index, column_index in coordinates]


def reflect_coordinates_vertically(
    coordinates: list[TileCoordinate],
    row_count: int,
) -> list[TileCoordinate]:
    return [(row_count - 1 - row_index, column_index) for row_index, column_index in coordinates]


def replace_row_invalid_spans(
    spans: list[tuple[int, int, int]],
    row_index: int,
    replacement_spans: list[tuple[int, int, int]],
) -> list[tuple[int, int, int]]:
    filtered_spans = [span for span in spans if span[0] != row_index]
    return filtered_spans + replacement_spans


